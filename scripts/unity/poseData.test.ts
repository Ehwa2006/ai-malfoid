// 유니티 VR 앱(unity/MalfoidVR)이 웹 앱과 같은 몸짓·표정을 쓰도록 C# 표를 만든다.
// 몸짓·표정 표(src/three/vrmGestures.ts, src/three/vrm.ts, src/three/pose.ts, src/avatar2d/gestures.ts)를 고쳤으면
//   npm run unity:data
// 로 다시 만든다. 다시 만들지 않으면 이 테스트가 실패한다 (npm test).
// 수치는 three.js 좌표 그대로 적는다(+x가 캐릭터의 왼쪽). 유니티 쪽(NormalizedRig.cs)이 x를 뒤집어 쓴다.
import { describe, expect, it } from 'vitest'
import { EMOTIONS } from '../../src/lib/markers'
import { SCENE_INFO, SCENES } from '../../src/lib/scenes'
import { GESTURES, type GestureId, HABITS, NEEDS_TEA, RELAXED, SCENE_GESTURE, gesture } from '../../src/avatar2d/gestures'
import { FINGERS, POSES_3D, type ArmTarget } from '../../src/three/vrmGestures'
import { BLUSH, EXPRESSIONS, PROP_POSE, REST_POSE, SCENE_RIM } from '../../src/three/vrm'
import { HEAD_POSE } from '../../src/three/pose'

const OUT = '../../unity/MalfoidVR/Assets/Malfoid/Scripts/Generated/PoseData.cs'

const f = (n: number) => {
  const s = Number(n.toFixed(4)).toString()
  return `${s.includes('.') || s.includes('e') ? s : `${s}.0`}f`
}
const v3 = ([x, y, z]: readonly number[]) => `new Vector3(${f(x)}, ${f(y)}, ${f(z)})`
const str = (s: string | null | undefined) => (s == null ? 'null' : JSON.stringify(s))
const pascal = (s: string) => s[0].toUpperCase() + s.slice(1)

function target(t: ArmTarget | undefined): string {
  if (!t)
    return 'null'
  return `new ArmTarget(Anchor.${pascal(t.anchor)}, ${v3(t.at)}, ${v3(t.pole)}, ${v3(t.hand ?? [0, 0, 0])}, ${str(t.fingers ?? 'relaxed')})`
}

/** 한동안 조용할 때 하는 버릇 후보 (감정 × 장소). pickHabit과 같은 규칙 */
function habitPool(emotion: (typeof EMOTIONS)[number], scene: (typeof SCENES)[number]): GestureId[] {
  const extra = SCENE_GESTURE[scene]
  const pool = extra && RELAXED.includes(emotion) ? [...HABITS[emotion], extra] : HABITS[emotion]
  return pool.filter(id => id !== 'teacup' || NEEDS_TEA.includes(scene))
}

export function renderPoseData(): string {
  const ids = Object.keys(GESTURES) as GestureId[]
  const lines: string[] = []
  const out = (s = '') => lines.push(s)
  out('// <auto-generated>')
  out('// npm run unity:data 로 웹 앱의 몸짓·표정 표에서 만든 파일이다. 직접 고치지 말고 원래 표를 고친 뒤 다시 만든다.')
  out('//   src/three/vrmGestures.ts, src/three/vrm.ts, src/three/pose.ts, src/avatar2d/gestures.ts')
  out('// 좌표와 회전은 three.js 기준(+x가 캐릭터의 왼쪽) 그대로다. NormalizedRig가 유니티 좌표로 바꿔 쓴다.')
  out('// </auto-generated>')
  out('using System.Collections.Generic;')
  out('using UnityEngine;')
  out()
  out('namespace Malfoid')
  out('{')
  out('    public static partial class PoseData')
  out('    {')
  out(`        public static readonly string[] Emotions = { ${EMOTIONS.map(str).join(', ')} };`)
  out(`        public static readonly string[] Scenes = { ${SCENES.map(str).join(', ')} };`)
  out(`        public static readonly string[] GestureIds = { ${ids.map(str).join(', ')} };`)
  out()
  out('        /** 장소 이름 */')
  out(`        public static readonly Dictionary<string, string> SceneLabels = new Dictionary<string, string> { ${SCENES.map(sc => `[${str(sc)}] = ${str(SCENE_INFO[sc].label)}`).join(', ')} };`)
  out('        /** 장소의 빛이 머리카락·옷 가장자리에 닿는 색 */')
  out(`        public static readonly Dictionary<string, string> SceneRim = new Dictionary<string, string> { ${SCENES.map(sc => `[${str(sc)}] = ${str(SCENE_RIM[sc])}`).join(', ')} };`)
  out()
  out('        /** 몸짓마다 손목 목표 (머리·가슴 기준) */')
  out('        public static readonly Dictionary<string, ArmPose> Poses = new Dictionary<string, ArmPose>')
  out('        {')
  for (const id of ids) {
    const p = POSES_3D[id]
    out(`            [${str(id)}] = new ArmPose(${target(p.left)}, ${target(p.right)}),`)
  }
  out('        };')
  out()
  out('        /** 손가락 굽힘 (0: 폄, 1: 꽉 쥠): 엄지, 검지, 중지, 약지, 새끼 */')
  out('        public static readonly Dictionary<string, float[]> Fingers = new Dictionary<string, float[]>')
  out('        {')
  for (const [k, c] of Object.entries(FINGERS))
    out(`            [${str(k)}] = new[] { ${c.map(f).join(', ')} },`)
  out('        };')
  out()
  out('        /** T포즈에서 팔을 내린 쉬는 자세 (정규화 본의 회전, 라디안, three.js 오일러 XYZ) */')
  out('        public static readonly Dictionary<HumanBodyBones, Vector3> RestPose = new Dictionary<HumanBodyBones, Vector3>')
  out('        {')
  for (const [bone, r] of Object.entries(REST_POSE))
    out(`            [HumanBodyBones.${pascal(bone)}] = ${v3(r!)},`)
  out('        };')
  out()
  out('        /** 감정 → VRM 표준 표정 가중치 */')
  out('        public static readonly Dictionary<string, Dictionary<string, float>> Expressions = new Dictionary<string, Dictionary<string, float>>')
  out('        {')
  for (const e of EMOTIONS) {
    const w = Object.entries(EXPRESSIONS[e]).map(([k, v]) => `[${str(k)}] = ${f(v!)}`).join(', ')
    out(`            [${str(e)}] = new Dictionary<string, float> { ${w} },`)
  }
  out('        };')
  out()
  out('        /** 감정별 볼 홍조 세기 */')
  out(`        public static readonly Dictionary<string, float> Blush = new Dictionary<string, float> { ${EMOTIONS.map(e => `[${str(e)}] = ${f(BLUSH[e])}`).join(', ')} };`)
  out()
  out('        /** 감정별 고개 자세 (라디안): x+ 숙이기, y+ 캐릭터의 왼쪽으로 돌리기, z+ 갸웃 */')
  out(`        public static readonly Dictionary<string, Vector3> HeadPose = new Dictionary<string, Vector3> { ${EMOTIONS.map(e => `[${str(e)}] = ${v3([HEAD_POSE[e].x, HEAD_POSE[e].y, HEAD_POSE[e].z])}`).join(', ')} };`)
  out()
  out('        /** 몸짓의 고개·시선·얼굴·손 흔들기·소품 */')
  out('        public static readonly Dictionary<string, GestureInfo> Gestures = new Dictionary<string, GestureInfo>')
  out('        {')
  for (const id of ids) {
    const g = gesture(id)
    const h = g.head ?? {}
    out(`            [${str(id)}] = new GestureInfo(${str(id)}, ${f(h.yaw ?? 0)}, ${f(h.pitch ?? 0)}, ${f(h.roll ?? 0)}, ${g.gaze ? 'true' : 'false'}, new Vector2(${f(g.gaze?.x ?? 0)}, ${f(g.gaze?.y ?? 0)}), ${str(g.face?.closed ?? null)}, ${str(g.face?.mouth ?? null)}, ${f(g.face?.blush ?? 0)}, ${f(g.waveAmp ?? 0)}, ${str(g.prop ?? null)}),`)
  }
  out('        };')
  out()
  out('        /** 소품을 드는 자리: 손(두 손으로 드는 것은 두 손 사이)에서 떨어진 정도, 캐릭터 기준 회전(오일러 XYZ) */')
  out('        public static readonly Dictionary<string, PropPose> Props = new Dictionary<string, PropPose>')
  out('        {')
  for (const [id, p] of Object.entries(PROP_POSE))
    out(`            [${str(id)}] = new PropPose(${v3(p.at)}, ${v3(p.rot)}, ${p.both ? 'true' : 'false'}),`)
  out('        };')
  out()
  out('        /** 한동안 조용할 때 하는 버릇 후보: 감정 → 장소 → 몸짓들 */')
  out('        public static readonly Dictionary<string, Dictionary<string, string[]>> Habits = new Dictionary<string, Dictionary<string, string[]>>')
  out('        {')
  for (const e of EMOTIONS) {
    const byScene = SCENES.map(sc => `[${str(sc)}] = new[] { ${habitPool(e, sc).map(str).join(', ')} }`).join(', ')
    out(`            [${str(e)}] = new Dictionary<string, string[]> { ${byScene} },`)
  }
  out('        };')
  out('    }')
  out('}')
  return `${lines.join('\n')}\n`
}

describe('unity pose data', () => {
  it('matches the web app tables (npm run unity:data to regenerate)', async () => {
    await expect(renderPoseData()).toMatchFileSnapshot(OUT)
  })
})
